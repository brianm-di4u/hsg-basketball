// Content-hashed output files for the game's core (vendor/three.<h>.js, assets/players.<h>.js, assets/tex.<h>.js).
// The site caches game files for an hour under fixed names, and serves hashed names as immutable, so a new
// build can never mix with a stale copy of an old one. Every build script writes through here, then
// writeBuildInfo() records the current names in src/js/gl/build-info.js, which the inliner bundles.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const GAME = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
// bumped when the core and the HQ manifest stop being compatible (src/js/gl/hq.js checks it)
export const SCHEMA = 3;
const CORE = { three: ['vendor', 'three'], players: ['assets', 'players'], tex: ['assets', 'tex'] };

export const hash8 = (buf) => crypto.createHash('sha256').update(buf).digest('hex').slice(0, 8);

// Write `<dir>/<base>.<hash8><ext>` and delete older hashed copies of the same base. Returns the repo path.
export function writeHashed(dir, base, ext, content) {
  const buf = Buffer.isBuffer(content) ? content : Buffer.from(content);
  const name = `${base}.${hash8(buf)}${ext}`;
  const abs = path.join(GAME, dir);
  fs.mkdirSync(abs, { recursive: true });
  const re = new RegExp(`^${base}\\.[0-9a-f]{8}${ext.replace('.', '\\.')}$`);
  for (const f of fs.readdirSync(abs)) if (re.test(f) && f !== name) fs.rmSync(path.join(abs, f));
  fs.writeFileSync(path.join(abs, name), buf);
  return `${dir}/${name}`;
}

// The current hashed name of each core file, found on disk.
export function coreFiles() {
  const out = {};
  for (const [key, [dir, base]] of Object.entries(CORE)) {
    const abs = path.join(GAME, dir);
    const f = fs.existsSync(abs) && fs.readdirSync(abs).find((x) => new RegExp(`^${base}\\.[0-9a-f]{8}\\.js$`).test(x));
    if (!f) throw new Error(`no hashed ${dir}/${base}.<hash>.js: run the build script that makes it`);
    out[key] = `${dir}/${f}`;
  }
  return out;
}

export function writeBuildInfo() {
  const core = coreFiles();
  const src = `// GENERATED by tools/hashed.mjs (build-vendor, pack-assets). Do not edit.\n`
    + `// The core files' content-hashed names and the HQ manifest schema they expect.\n`
    + `export const CORE = ${JSON.stringify({ ...core, schema: SCHEMA }, null, 2)};\n`;
  fs.writeFileSync(path.join(GAME, 'src', 'js', 'gl', 'build-info.js'), src);
  return core;
}
